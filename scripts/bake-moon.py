"""Bake NASA's LROC map to a synchronous, north-up near-side ASCII texture.

Development only: pip install Pillow, then python scripts/bake-moon.py.
Source and credit: NASA's Scientific Visualization Studio, CGI Moon Kit
https://svs.gsfc.nasa.gov/4720/ (2025 color map, LROC / LOLA).
"""
import base64
import io
import math
from pathlib import Path
import urllib.request

from PIL import Image

SOURCE = 'https://svs.gsfc.nasa.gov/vis/a000000/a004700/a004720/lroc_color_2k.jpg'
SIZE = 192


def bake(data):
    image = Image.open(io.BytesIO(data)).convert('L')
    width, height = image.size
    pixels = image.load()
    values = []
    for y in range(SIZE):
        v = (y + 0.5) / SIZE * 2 - 1
        for x in range(SIZE):
            u = (x + 0.5) / SIZE * 2 - 1
            if u * u + v * v > 1:
                values.append(0)
                continue
            # Orthographic near side: west left, lunar north up. No mirror
            # or arbitrary rotation. Tycho falls below and left of centre.
            longitude = math.atan2(u, math.sqrt(1 - u * u - v * v))
            latitude = math.asin(-v)
            px = (longitude / (2 * math.pi) + 0.5) * width - 0.5
            py = (0.5 - latitude / math.pi) * height - 0.5
            ix, iy = math.floor(px), math.floor(py)
            fx, fy = px - ix, py - iy
            def sample(dx, dy):
                return pixels[(ix + dx) % width, max(0, min(height - 1, iy + dy))]
            value = ((sample(0, 0) * (1 - fx) + sample(1, 0) * fx) * (1 - fy)
                     + (sample(0, 1) * (1 - fx) + sample(1, 1) * fx) * fy)
            values.append(round(value))
    # Preserve 8-bit albedo so small craters and ejecta survive resampling.
    encoded = base64.b64encode(bytes(values)).decode('ascii')
    lines = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    output = "// Generated by scripts/bake-moon.py. NASA SVS / LROC / LOLA.\n"
    output += "// Source: https://svs.gsfc.nasa.gov/4720/\n"
    output += "// Orthographic near side, lunar north up; 192 x 192, 8-bit albedo.\n"
    output += f"export const MOON_MAP_SIZE = {SIZE};\n"
    output += "export const MOON_MAP = Uint8Array.from(atob(\n"
    output += ' +\n'.join("  '" + line + "'" for line in lines)
    output += "\n), ch => ch.charCodeAt(0));\n"
    target = Path(__file__).resolve().parents[1] / 'src/world/moon-map.js'
    target.write_text(output, encoding='utf-8', newline='\n')
    print(f'Baked {SIZE} x {SIZE} north-up near side to {target.name}')


if __name__ == '__main__':
    with urllib.request.urlopen(SOURCE) as response:
        bake(response.read())
