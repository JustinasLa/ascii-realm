function score({ id, title, bpm, key, chords, melody, instrument }) {
  const events = [];
  const add = (beat, note, beats, part) => {
    events.push(Object.freeze({ beat, note, beats, part, ...instruments[part] }));
  };
  chords.forEach((chord, bar) => {
    // The three quiet upper voices move only at bar boundaries.
    chord.forEach(note => add(bar * 4, note + 12, 4, 'pad'));
    add(bar * 4, chord[0] - 12, 3.5, 'bass');
    for (const [offset, note, beats] of melody[bar]) {
      add(bar * 4 + offset, note, beats, instrument);
      // A breathy answering voice appears once per four-bar phrase by day.
      if (id === 'day' && bar % 4 === 3 && offset === 0) {
        add(bar * 4 + 2, note + 12, 1.5, 'flute');
      }
      // A quiet octave partial gives the night bells their music-box color.
      if (id === 'night') {
        events.push(Object.freeze({
          beat: bar * 4 + offset, note: note + 12, beats: beats * 0.55,
          part: 'bell', type: 'sine', gain: 0.008, attack: 0.003, length: 0.72,
        }));
      }
    }
  });
  events.sort((a, b) => a.beat - b.beat);
  return Object.freeze({ id, title, bpm, key, bars: 16, beats: 64,
    duration: 64 * 60 / bpm, events: Object.freeze(events) });
}

